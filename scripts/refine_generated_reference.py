def refine_reference_docs(project_root=None):
    u"""整理全部真实生成 API 页面的概览与 Callable“作用”区块。"""
    if project_root is None:
        project_root = get_project_root()

    markdown_files = iter_generated_reference_files(
        project_root
    )

    if not markdown_files:
        raise RuntimeError(
            u"没有找到自动生成 API 页面，请先执行 generate_mkdocs_reference.py。"
        )

    changed_pages = 0
    callable_purpose_labels = 0

    for markdown_path in markdown_files:
        with open(
                markdown_path,
                "r",
                encoding="utf-8"
        ) as file_object:
            markdown_text = file_object.read()

        source_path = get_source_path_from_reference(
            project_root,
            markdown_path
        )
        summary = build_summary_from_source(
            source_path
        )

        if not summary:
            summary = extract_summary_from_overview(
                markdown_text
            )

        position = build_module_position(
            markdown_path,
            project_root
        )

        refined_text = replace_overview(
            markdown_text,
            summary,
            position
        )
        refined_text, purpose_count = add_callable_purpose_labels(
            refined_text
        )

        callable_purpose_labels += purpose_count

        if refined_text == markdown_text:
            continue

        with open(
                markdown_path,
                "w",
                encoding="utf-8",
                newline="\n"
        ) as file_object:
            file_object.write(
                refined_text
            )

        changed_pages += 1

    print(
        u"Generated API pages scanned: {}".format(
            len(markdown_files)
        )
    )
    print(
        u"Refined API pages:          {}".format(
            changed_pages
        )
    )
    print(
        u"Added callable purposes:    {}".format(
            callable_purpose_labels
        )
    )

    return {
        "scanned_pages": len(markdown_files),
        "changed_pages": changed_pages,
        "callable_purpose_labels": callable_purpose_labels,
    }


if __name__ == "__main__":
    refine_reference_docs()
