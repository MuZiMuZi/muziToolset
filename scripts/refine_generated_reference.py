def is_underline_heading(line):
    u"""判断一行是否是 ReStructuredText 风格标题下划线。"""
    stripped_line = line.strip()

    if not stripped_line:
        return False

    characters = set(stripped_line)

    if characters == set("="):
        return True

    if characters == set("-"):
        return True

    return False


def looks_like_section_title(paragraph):
    u"""判断自然段是否更像章节标题，而不是模块用途摘要。"""
    section_titles = [
        "模块职责",
        "当前公开方法",
        "公开类",
        "主要公开方法",
        "兼容辅助方法",
        "数据流",
        "本模块不负责",
        "设计原则",
        "正式模块路径",
        "生成范围",
        "说明",
        "功能",
        "使用场景",
        "职责",
        "边界",
        "负责",
        "使用",
    ]

    normalized = paragraph.strip().rstrip(":：")

    if normalized in section_titles:
        return True

    if len(normalized) <= 18:
        for title in section_titles:
            if title in normalized:
                return True

    # ``Animation Utils``、``Face Guide`` 这一类英文模块标题不适合作为用途。
    if len(normalized) <= 48:
        if re.match(
                r"^[A-Za-z0-9_ /.+-]+$",
                normalized
        ):
            return True

    return False


def get_docstring_paragraphs(docstring):
    u"""把 Module Docstring 整理成可用于摘要选择的自然段。"""
    if not docstring:
        return []

    raw_lines = docstring.expandtabs(4).strip().splitlines()
    clean_lines = []
    line_index = 0

    while line_index < len(raw_lines):
        line = raw_lines[line_index]
        stripped_line = line.strip()
        next_line = ""

        if line_index + 1 < len(raw_lines):
            next_line = raw_lines[line_index + 1]

        if stripped_line and is_underline_heading(next_line):
            line_index += 2
            continue

        if is_underline_heading(line):
            line_index += 1
            continue

        clean_lines.append(
            line.rstrip()
        )
        line_index += 1

    paragraphs = []
    current_lines = []

    for line in clean_lines:
        stripped_line = line.strip()

        if not stripped_line:
            if current_lines:
                paragraphs.append(
                    " ".join(current_lines).strip()
                )
                current_lines = []
            continue

        current_lines.append(
            stripped_line
        )

    if current_lines:
        paragraphs.append(
            " ".join(current_lines).strip()
        )

    return paragraphs


def trim_summary(summary):
    u"""把用途摘要控制在最多两句话、140 字符以内。"""
    summary = " ".join(
        summary.split()
    ).strip()

    if not summary:
        return summary

    sentence_parts = re.split(
        r"(?<=[。！？.!?])\s*",
        summary
    )
    selected_sentences = []

    for sentence in sentence_parts:
        sentence = sentence.strip()

        if not sentence:
            continue

        selected_sentences.append(
            sentence
        )

        if len(selected_sentences) >= 2:
            break

    if selected_sentences:
        summary = " ".join(
            selected_sentences
        )

    if len(summary) > MAX_SUMMARY_LENGTH:
        summary = summary[:MAX_SUMMARY_LENGTH - 3].rstrip()
        summary += "..."

    return summary


def build_summary_from_source(source_path):
    u"""从对应 Runtime 源码的 Module Docstring 中提取简短用途。"""
    if not source_path:
        return ""

    with open(
            source_path,
            "r",
            encoding="utf-8"
    ) as file_object:
        source_text = file_object.read()

    module_tree = ast.parse(
        source_text,
        filename=source_path
    )
    module_docstring = ast.get_docstring(
        module_tree
    ) or ""

    paragraphs = get_docstring_paragraphs(
        module_docstring
    )

    for paragraph in paragraphs:
        if looks_like_section_title(paragraph):
            continue

        if paragraph.startswith("``"):
            continue

        summary = trim_summary(
            paragraph
        )

        if summary:
            return summary

    return ""


def extract_summary_from_overview(markdown_text):
    u"""没有单一源码来源时，从现有生成概览选择一个简短摘要。"""
    start_marker = "## 概览"
    end_marker = "## 常用任务"

    start_index = markdown_text.find(
        start_marker
    )
    end_index = markdown_text.find(
        end_marker
    )

    if start_index < 0 or end_index <= start_index:
        return "MuziTools 自动生成的 API Reference 分类页面。"

    overview_text = markdown_text[
        start_index + len(start_marker):end_index
    ]
    paragraphs = overview_text.split("\n\n")

    for paragraph in paragraphs:
        paragraph = " ".join(
            paragraph.split()
        ).strip()

        if not paragraph:
            continue

        if paragraph.startswith("**"):
            continue

        if paragraph.startswith("#"):
            continue

        if looks_like_section_title(paragraph):
            continue

        summary = trim_summary(
            paragraph
        )

        if summary:
            return summary

    return "MuziTools 自动生成的 API Reference 分类页面。"


def build_module_position(markdown_path, project_root):
    u"""根据真实 API 页面目录生成简洁的模块层级定位。"""
    reference_root = get_reference_root(
        project_root
    )
    relative_path = os.path.relpath(
        markdown_path,
        reference_root
    )
    relative_path = relative_path.replace(
        "\\",
        "/"
    )

    if relative_path.startswith("core/"):
        return u"Core 底层公共能力；不负责 UI 和完整 Rig Workflow。"

    if relative_path.startswith("systems/"):
        return u"System 业务构建层；负责可重复构建的完整 Rig Component 或 Workflow。"

    if relative_path.startswith("tools/"):
        return u"Tool 用户操作层；负责 UI、Selection 和调用底层能力。"

    if relative_path.startswith("ui/"):
        return u"UI 公共层；负责可复用界面组件，不承载 Rig 算法。"

    if relative_path.startswith("app/"):
        return u"应用入口层；负责主工具箱、窗口生命周期和工具调度。"

    return u"MuziTools 包级入口、配置或 API 分类页面。"


