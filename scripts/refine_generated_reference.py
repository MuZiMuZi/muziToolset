def replace_overview(markdown_text, summary, position):
    u"""把页面概览统一替换为简短的“用途 / 模块定位”。"""
    start_marker = "## 概览"
    end_marker = "## 常用任务"

    start_index = markdown_text.find(
        start_marker
    )
    end_index = markdown_text.find(
        end_marker
    )

    if start_index < 0:
        return markdown_text

    if end_index < 0:
        return markdown_text

    if end_index <= start_index:
        return markdown_text

    overview_lines = [
        "## 概览",
        "",
        "**用途**",
        "",
        summary,
        "",
        "**模块定位**",
        "",
        position,
        "",
    ]
    overview_text = "\n".join(
        overview_lines
    )

    return (
        markdown_text[:start_index]
        + overview_text
        + markdown_text[end_index:]
    )


def add_callable_purpose_labels(markdown_text):
    u"""在每一个 Function / Method 标题后的功能摘要前插入“作用”。"""
    lines = markdown_text.splitlines()
    result_lines = []
    changed_count = 0
    line_index = 0

    while line_index < len(lines):
        line = lines[line_index]
        result_lines.append(
            line
        )

        if not CALLABLE_HEADING_PATTERN.match(line):
            line_index += 1
            continue

        next_index = line_index + 1

        while next_index < len(lines):
            if lines[next_index].strip():
                break

            result_lines.append(
                lines[next_index]
            )
            next_index += 1

        if next_index >= len(lines):
            line_index = next_index
            continue

        if lines[next_index].strip() == "**作用**":
            line_index = next_index
            continue

        result_lines.append(
            "**作用**"
        )
        result_lines.append("")
        changed_count += 1
        line_index = next_index

    refined_text = "\n".join(
        result_lines
    )

    if markdown_text.endswith("\n"):
        refined_text += "\n"

    return refined_text, changed_count


