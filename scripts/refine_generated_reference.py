def get_source_path_from_reference(project_root, markdown_path):
    u"""
    根据生成页面路径反向取得对应 Runtime Python 源码。

    映射示例：
        ``docs/reference/core/attr_utils.md``
            -> ``core/attr_utils.py``

        ``docs/reference/systems/face/package.md``
            -> ``systems/face/__init__.py``

        ``docs/reference/package.md``
            -> ``__init__.py``

    分类 ``index.md`` 没有单一源码来源，因此返回 None。
    """
    reference_root = get_reference_root(
        project_root
    )
    relative_path = os.path.relpath(
        markdown_path,
        reference_root
    )
    relative_path = relative_path.replace(
        "\\",
        "/"
    )

    if relative_path == "package.md":
        source_path = os.path.join(
            project_root,
            "__init__.py"
        )

    elif relative_path == "config.md":
        source_path = os.path.join(
            project_root,
            "config.py"
        )

    elif relative_path.endswith("/package.md"):
        package_directory = relative_path[:-len("/package.md")]
        source_path = os.path.join(
            project_root,
            package_directory,
            "__init__.py"
        )

    elif relative_path.endswith("/index.md"):
        return None

    else:
        source_relative_path = os.path.splitext(
            relative_path
        )[0] + ".py"
        source_path = os.path.join(
            project_root,
            source_relative_path
        )

    if not os.path.isfile(source_path):
        return None

    return source_path


