# coding=utf-8
u"""
Generated API Reference Refiner
===============================

直接整理 ``docs/reference`` 中真实生成出来的 API Markdown 页面。

负责：
    1. 模块“概览”只保留简短用途说明；
    2. 概览固定分成“用途”和“模块定位”；
    3. 不把完整 Module Docstring 正文直接铺在页面顶部；
    4. 每一个公开 Function / Method 标题下面固定增加“作用”区块；
    5. 保持 Signature、参数、返回值、异常、示例和 Notes 不变。

设计说明：
    本脚本不再依赖 Generator 的“源码路径 -> 输出路径”推算。
    Generator 完成后直接扫描实际生成的 Markdown，因此新增目录、Package Page
    或 Generator 输出规则调整时，不会因为路径映射过期而静默漏处理页面。

使用顺序：
    python scripts/generate_mkdocs_reference.py
    python scripts/refine_generated_reference.py
"""

from __future__ import print_function

import ast
import os
import re


GENERATED_MARKER = "<!-- AUTO-GENERATED BY scripts/generate_mkdocs_reference.py -->"
MAX_SUMMARY_LENGTH = 140

CALLABLE_HEADING_PATTERN = re.compile(
    r"^(#{3,6})\s+`[^`]+\(\)`\s*$"
)


# =============================================================================
# Project
# =============================================================================

def get_project_root():
    u"""返回 MuziTools 仓库根目录。"""
    script_directory = os.path.dirname(
        os.path.abspath(__file__)
    )

    return os.path.dirname(
        script_directory
    )


def get_reference_root(project_root):
    u"""返回自动生成 API Reference 的根目录。"""
    return os.path.join(
        project_root,
        "docs",
        "reference"
    )


def iter_generated_reference_files(project_root):
    u"""遍历 ``docs/reference`` 下全部真实自动生成 Markdown 页面。"""
    reference_root = get_reference_root(
        project_root
    )
    result = []

    if not os.path.isdir(reference_root):
        return result

    for root_directory, folder_names, file_names in os.walk(reference_root):
        if "__pycache__" in folder_names:
            folder_names.remove(
                "__pycache__"
            )

        for file_name in file_names:
            if not file_name.endswith(".md"):
                continue

            file_path = os.path.join(
                root_directory,
                file_name
            )

            with open(
                    file_path,
                    "r",
                    encoding="utf-8"
            ) as file_object:
                prefix = file_object.read(512)

            if GENERATED_MARKER not in prefix:
                continue

            result.append(
                file_path
            )

    result.sort()
    return result


