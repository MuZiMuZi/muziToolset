def get_output_relative_path(module_info):
    """计算源码文件对应的 ``docs/reference`` 输出路径。"""
    relative_source = module_info[
        "relative_path"
    ]

    if relative_source == "__init__.py":
        return "package.md"

    if relative_source.endswith("/__init__.py"):
        package_directory = os.path.dirname(
            relative_source
        )

        return os.path.join(
            package_directory,
            "package.md"
        )

    relative_without_extension = os.path.splitext(
        relative_source
    )[0]

    return relative_without_extension + ".md"


def write_text_file(file_path, content):
    """写入 UTF-8 文本，并自动创建父目录。"""
    parent_directory = os.path.dirname(
        file_path
    )

    if not os.path.isdir(parent_directory):
        os.makedirs(
            parent_directory
        )

    with open(
            file_path,
            "w",
            encoding="utf-8",
            newline="\n"
    ) as file_object:
        file_object.write(
            content
        )


def build_reference_tree(module_items, category_name):
    """把模块列表整理成按源码目录分组的 Reference Index。"""
    grouped_items = {}

    for module_info, output_path in module_items:
        relative_path = module_info[
            "relative_path"
        ]

        if category_name == "package":
            group_name = "Package"
        else:
            relative_from_category = os.path.relpath(
                relative_path,
                category_name
            ).replace(
                "\\",
                "/"
            )

            group_directory = os.path.dirname(
                relative_from_category
            )

            if not group_directory:
                group_name = "基础模块"
            else:
                group_name = group_directory

        if group_name not in grouped_items:
            grouped_items[group_name] = []

        grouped_items[group_name].append(
            (module_info, output_path)
        )

    return grouped_items


def build_reference_index(
        title,
        description,
        module_items,
        docs_root,
        category_name
):
    """生成一个 API 分类索引。"""
    lines = []
    lines.append(
        generated_marker
    )
    lines.append("")
    lines.append(
        "# {}".format(
            title
        )
    )
    lines.append("")
    lines.append(
        description
    )
    lines.append("")

    grouped_items = build_reference_tree(
        module_items,
        category_name
    )

    group_names = list(
        grouped_items.keys()
    )
    group_names.sort()

    for group_name in group_names:
        lines.append(
            "## {}".format(
                group_name
            )
        )
        lines.append("")

        index_directory = os.path.join(
            docs_root,
            "reference",
            category_name
        )

        if category_name == "package":
            index_directory = os.path.join(
                docs_root,
                "reference"
            )

        group_items = grouped_items[
            group_name
        ]

        def get_group_item_sort_key(item):
            """返回 Reference Index 项目的稳定排序键。"""
            module_info = item[0]
            return module_info["relative_path"]

        group_items.sort(
            key=get_group_item_sort_key
        )

        for module_info, output_path in group_items:
            relative_link = os.path.relpath(
                output_path,
                index_directory
            ).replace(
                "\\",
                "/"
            )

            summary = (
                module_info["summary"]
                or "查看该文件的公开 API。"
            )

            lines.append(
                "- [`{}`]({}) — {}".format(
                    module_info["relative_path"],
                    relative_link,
                    summary
                )
            )

        lines.append("")

    return "\n".join(
        lines
    )


def clean_generated_reference(reference_root):
    """删除旧自动生成页面，但保留手写 User Guide。"""
    if not os.path.isdir(reference_root):
        return

    for root_directory, folder_names, file_names in os.walk(reference_root):
        for file_name in file_names:
            if not file_name.endswith(".md"):
                continue

            file_path = os.path.join(
                root_directory,
                file_name
            )

            try:
                with open(
                        file_path,
                        "r",
                        encoding="utf-8"
                ) as file_object:
                    first_content = file_object.read(
                        512
                    )
            except OSError:
                continue

            if generated_marker not in first_content:
                continue

            os.remove(
                file_path
            )

    for root_directory, folder_names, file_names in os.walk(
            reference_root,
            topdown=False
    ):
        if root_directory == reference_root:
            continue

        if os.listdir(root_directory):
            continue

        shutil.rmtree(
            root_directory
        )


