# coding=utf-8
u"""
MkDocs Reference Generator
==========================

MuziTools 的静态 API 文档生成器。

模块职责
--------
这个脚本使用 Python 标准库 ``ast`` 直接读取源码，不 import Maya 模块，
因此可以在普通 Python、GitHub Actions 或本地文档环境中运行。

当前公开方法
------------
    get_project_root()
        获取仓库根目录。

    get_docs_root(project_root)
        获取 docs 目录。

    iter_source_files(project_root)
        扫描 core / tools / systems 中的正式 Python 模块。

    source_path_to_module_name(project_root, source_path)
        将源码路径转换成真实 Python Import Path。

    read_source_text(source_path)
        读取 UTF-8 Python 源码。

    get_first_paragraph(docstring)
        从 Docstring 中取得第一段功能摘要。

    get_node_doc_summary(node)
        获取函数 / 类 Docstring 第一段摘要。

    format_ast_value(node)
        将 AST 默认值或 Annotation 转成可读字符串。

    format_function_signature(function_node)
        从 AST FunctionDef 生成函数签名。

    collect_class_api(class_node)
        收集一个公开类及其公开方法。

    collect_module_info(project_root, source_path)
        解析一个 Python 模块的 Docstring、函数、类和 API 信息。

    build_usage_scenarios(module_info)
        根据模块所属层级和名称生成第一版“使用场景”。

    build_example(module_info)
        根据模块类型生成安全的第一版 Import / main() 示例。

    build_module_markdown(module_info)
        生成单模块“功能 + 使用场景 + API + 示例”Markdown。

    write_text_file(file_path, content)
        写入 UTF-8 文本文档，并自动创建父目录。

    build_reference_index(title, description, module_items, docs_root)
        生成 Core / Tools / Systems 分类索引。

    clean_generated_reference(reference_root)
        删除旧的自动生成模块页，避免删除手写说明页。

    generate_reference_docs(project_root=None)
        扫描正式源码并生成全部第一版 API Reference。

    main()
        命令行入口。

生成范围
--------
    core/**/*.py
    tools/**/*.py
    systems/**/*.py

默认跳过
--------
    __init__.py
    __pycache__
    私有文件（文件名以 _ 开头）
    legacy_reference/
    tests/

生成页面结构
------------
每一个正式模块会生成：

    # 模块 Import Path
    ## 功能
    ## 使用场景
    ## API
    ## 示例
    ## 源码位置

设计原则
--------
1. 不 import Maya，避免 ``maya.cmds`` 导致在线构建失败；
2. 只依赖 Python 标准库，Maya 2023 自带 Python 也可以运行；
3. 自动文档只是第一版骨架，复杂 Rig Workflow 仍建议补手写说明；
4. 生成文件顶部带 AUTO-GENERATED 标记，避免误把自动页当手写源码；
5. ``docs/reference/*/index.md`` 同样由生成器维护，MkDocs Nav 保持稳定。
"""

from __future__ import print_function

import ast
import os
import shutil


# =============================================================================
# 配置
# =============================================================================

# 只扫描正式运行架构。
source_roots = [
    "core",
    "tools",
    "systems",
]

# 自动生成页面头部标记。
generated_marker = "<!-- AUTO-GENERATED BY scripts/generate_mkdocs_reference.py -->"


# =============================================================================
# Project Path
# =============================================================================

def get_project_root():
    """返回当前脚本所在 MuziTools 仓库的根目录。"""
    # 步骤 1：取得 scripts/ 目录。
    script_directory = os.path.dirname(
        os.path.abspath(__file__)
    )

    # 步骤 2：scripts 的父目录就是仓库根目录。
    project_root = os.path.dirname(script_directory)
    return project_root


def get_docs_root(project_root):
    """返回项目 docs 目录绝对路径。"""
    return os.path.join(
        project_root,
        "docs"
    )


