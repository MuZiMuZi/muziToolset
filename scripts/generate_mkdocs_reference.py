def iter_source_files(project_root):
    """
    扫描正式 ``core / tools / systems`` 中的 Python 模块。

    Returns:
        list: 排序后的 Python 文件绝对路径。
    """
    source_files = []

    # -------------------------------------------------------------------------
    # 步骤 1：逐个正式源码根目录扫描。
    # -------------------------------------------------------------------------
    for source_root_name in source_roots:
        source_root = os.path.join(
            project_root,
            source_root_name
        )

        if not os.path.isdir(source_root):
            continue

        # ---------------------------------------------------------------------
        # 步骤 2：递归寻找 Python 文件。
        # ---------------------------------------------------------------------
        for root_directory, folder_names, file_names in os.walk(source_root):
            # 不扫描 __pycache__。
            if "__pycache__" in folder_names:
                folder_names.remove("__pycache__")

            for file_name in file_names:
                if not file_name.endswith(".py"):
                    continue

                # __init__.py 主要负责包入口，不单独生成模块页。
                if file_name == "__init__.py":
                    continue

                # 以下划线开头的内部文件默认不作为公开模块文档。
                if file_name.startswith("_"):
                    continue

                source_path = os.path.join(
                    root_directory,
                    file_name
                )
                source_files.append(source_path)

    # -------------------------------------------------------------------------
    # 步骤 3：排序，保证每次生成结果稳定。
    # -------------------------------------------------------------------------
    source_files.sort()
    return source_files


def source_path_to_module_name(project_root, source_path):
    """
    将源码路径转换成真实 Python Import Path。

    Example:
        core/animation_utils.py
            -> muziToolset.core.animation_utils
    """
    # 步骤 1：取得相对仓库路径。
    relative_path = os.path.relpath(
        source_path,
        project_root
    )

    # 步骤 2：去掉 .py，并把路径分隔符换成点号。
    module_path = os.path.splitext(relative_path)[0]
    module_path = module_path.replace("\\", ".")
    module_path = module_path.replace("/", ".")

    # 步骤 3：正式包名固定为 muziToolset。
    return "muziToolset." + module_path


def read_source_text(source_path):
    """读取 UTF-8 Python 源码。"""
    with open(source_path, "r", encoding="utf-8") as file_object:
        return file_object.read()


