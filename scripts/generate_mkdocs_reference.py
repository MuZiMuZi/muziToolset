def get_navigation_display_name(name):
    """把源码目录 / 文件名称转换成更适合侧边栏显示的标题。"""
    special_names = {
        "app": "App",
        "core": "Core",
        "systems": "Systems",
        "tools": "Tools",
        "ui": "UI",
        "face": "Face",
        "eyelid": "Eyelid",
        "lip": "Lip",
        "controller": "Controller",
        "blendshape": "BlendShape",
        "skin": "Skin",
        "joint": "Joint",
        "basic": "Basic",
        "clean": "Clean",
        "rig": "Rig",
        "body": "Body",
        "skirt": "Skirt",
        "widgets": "Widgets",
    }

    if name in special_names:
        return special_names[name]

    display_name = name

    if display_name.endswith(".py"):
        display_name = display_name[:-3]

    display_name = display_name.replace(
        "_",
        " "
    )

    words = display_name.split()
    result_words = []

    for word in words:
        if not word:
            continue

        result_words.append(
            word[0].upper() + word[1:]
        )

    return " ".join(
        result_words
    )


def build_module_navigation_tree(
        module_infos,
        category_name
):
    """根据源码目录构建某个 API 分类的导航树。"""
    tree = {
        "__modules__": [],
    }

    for module_info in module_infos:
        if module_info["root_name"] != category_name:
            continue

        relative_path = module_info[
            "relative_path"
        ]

        if category_name == "package":
            path_parts = [
                relative_path
            ]
        else:
            relative_from_category = os.path.relpath(
                relative_path,
                category_name
            ).replace(
                "\\",
                "/"
            )

            path_parts = relative_from_category.split(
                "/"
            )

        current_tree = tree

        directory_parts = path_parts[:-1]
        file_name = path_parts[-1]

        for directory_name in directory_parts:
            if directory_name not in current_tree:
                current_tree[directory_name] = {
                    "__modules__": [],
                }

            current_tree = current_tree[
                directory_name
            ]

        current_tree["__modules__"].append({
            "file_name": file_name,
            "module_info": module_info,
        })

    return tree


def render_module_navigation_tree(
        tree,
        lines,
        indent_level
):
    """递归把模块导航树渲染成 mkdocs-literate-nav Markdown。"""
    indent = "    " * indent_level

    modules = tree.get(
        "__modules__",
        []
    )

    # Package 页面优先，其余按源码文件名排序。
    def get_module_sort_key(module_item):
        """返回导航中文件的稳定排序键。"""
        file_name = module_item[
            "file_name"
        ]

        if file_name == "__init__.py":
            return "0"

        return "1_" + file_name

    modules.sort(
        key=get_module_sort_key
    )

    for module_item in modules:
        module_info = module_item[
            "module_info"
        ]
        file_name = module_item[
            "file_name"
        ]

        output_relative_path = get_output_relative_path(
            module_info
        ).replace(
            "\\",
            "/"
        )

        link_path = "reference/" + output_relative_path

        if file_name == "__init__.py":
            display_name = "Package"
        else:
            display_name = "`{}`".format(
                file_name
            )

        lines.append(
            "{}* [{}]({})".format(
                indent,
                display_name,
                link_path
            )
        )

    directory_names = []

    for key in tree:
        if key == "__modules__":
            continue

        directory_names.append(
            key
        )

    directory_names.sort()

    for directory_name in directory_names:
        display_name = get_navigation_display_name(
            directory_name
        )

        lines.append(
            "{}* {}".format(
                indent,
                display_name
            )
        )

        child_tree = tree[
            directory_name
        ]

        render_module_navigation_tree(
            child_tree,
            lines,
            indent_level + 1
        )


