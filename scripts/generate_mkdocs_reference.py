def build_import_example(module_info):
    """生成模块 Import 示例。"""
    module_name = module_info["module_name"]

    if module_name == "muziToolset":
        return "import muziToolset"

    module_parts = module_name.split(".")
    short_name = module_parts[-1]
    parent_module = ".".join(
        module_parts[:-1]
    )

    return "from {} import {}".format(
        parent_module,
        short_name
    )


def build_parameter_placeholder(parameter):
    """根据参数元数据生成安全的示例占位值。"""
    parameter_name = parameter["name"].lower()
    parameter_type = (
        parameter["type"]
        or parameter["doc_type"]
        or ""
    ).lower()

    if parameter["default"]:
        return parameter["default"]

    if "bool" in parameter_type:
        return "True"

    if "int" in parameter_type:
        return "1"

    if "float" in parameter_type:
        return "1.0"

    if "list" in parameter_type or "tuple" in parameter_type:
        return "[]"

    if "dict" in parameter_type:
        return "{}"

    string_tokens = [
        "name",
        "node",
        "object",
        "target",
        "source",
        "parent",
        "child",
        "joint",
        "curve",
        "mesh",
        "model",
        "control",
        "ctrl",
        "attr",
        "path",
        "side",
    ]

    for token in string_tokens:
        if token in parameter_name:
            return '"{}"'.format(
                parameter["name"]
            )

    return "..."


def get_required_parameters(parameters, include_self=False):
    """返回调用示例需要展示的必要参数。"""
    result = []

    for parameter in parameters:
        parameter_name = parameter["name"]

        if not include_self:
            if parameter_name in ["self", "cls"]:
                continue

        if parameter["kind"] in ["vararg", "kwarg"]:
            continue

        if not parameter["required"]:
            continue

        result.append(
            parameter
        )

    return result


def build_callable_example(
        module_info,
        callable_info,
        class_info=None
):
    """为 Function / Method 生成最小安全调用示例。"""
    lines = []
    lines.append("```python")
    lines.append(
        build_import_example(
            module_info
        )
    )
    lines.append("")

    module_short_name = module_info[
        "module_name"
    ].split(".")[-1]

    required_parameters = get_required_parameters(
        callable_info["parameters"]
    )

    if class_info is not None:
        if callable_info["name"] == "__init__":
            class_name = class_info["name"]

            if required_parameters:
                lines.append(
                    "instance = {}.{}(".format(
                        module_short_name,
                        class_name
                    )
                )

                for parameter in required_parameters:
                    lines.append(
                        "    {}={}".format(
                            parameter["name"],
                            build_parameter_placeholder(
                                parameter
                            )
                        ) + ","
                    )

                lines.append(")")
            else:
                lines.append(
                    "instance = {}.{}()".format(
                        module_short_name,
                        class_name
                    )
                )

            lines.append("```")
            return "\n".join(lines)

    if class_info is None:
        call_name = "{}.{}".format(
            module_short_name,
            callable_info["name"]
        )

        if module_info["module_name"] == "muziToolset":
            call_name = "muziToolset.{}".format(
                callable_info["name"]
            )

    else:
        class_name = class_info["name"]
        constructor = class_info["constructor"]

        constructor_required = []

        if constructor:
            constructor_required = get_required_parameters(
                constructor["parameters"]
            )

        if constructor_required:
            lines.append(
                "{} = {}.{}(".format(
                    "instance",
                    module_short_name,
                    class_name
                )
            )

            for parameter in constructor_required:
                lines.append(
                    "    {}={}".format(
                        parameter["name"],
                        build_parameter_placeholder(
                            parameter
                        )
                    ) + ","
                )

            lines.append(")")
        else:
            lines.append(
                "instance = {}.{}()".format(
                    module_short_name,
                    class_name
                )
            )

        lines.append("")
        call_name = "instance.{}".format(
            callable_info["name"]
        )

    if required_parameters:
        lines.append(
            "result = {}(".format(
                call_name
            )
        )

        for parameter in required_parameters:
            lines.append(
                "    {}={}".format(
                    parameter["name"],
                    build_parameter_placeholder(
                        parameter
                    )
                ) + ","
            )

        lines.append(")")
    else:
        lines.append(
            "result = {}()".format(
                call_name
            )
        )

    lines.append("```")
    return "\n".join(lines)


def build_docstring_example(example_text):
    """把 Docstring Example 区域整理为 Markdown Python Code Block。"""
    if not example_text:
        return ""

    stripped_text = example_text.strip()

    if stripped_text.startswith("```"):
        return stripped_text

    lines = stripped_text.splitlines()
    clean_lines = []

    for line in lines:
        clean_line = line

        if clean_line.lstrip().startswith(">>> "):
            clean_line = clean_line.replace(
                ">>> ",
                "",
                1
            )

        elif clean_line.lstrip().startswith("... "):
            clean_line = clean_line.replace(
                "... ",
                "",
                1
            )

        clean_lines.append(
            clean_line
        )

    return "```python\n{}\n```".format(
        "\n".join(clean_lines)
    )


def build_parameter_table(callable_info):
    """生成一个 Function / Method 的参数表格。"""
    visible_parameters = []

    for parameter in callable_info["parameters"]:
        if parameter["name"] in ["self", "cls"]:
            continue

        visible_parameters.append(
            parameter
        )

    if not visible_parameters:
        return [
            "无。",
            "",
        ]

    lines = []
    lines.append(
        "| 参数 | 类型 | 必填 | 默认值 | 说明 |"
    )
    lines.append(
        "| --- | --- | :---: | --- | --- |"
    )

    for parameter in visible_parameters:
        parameter_type = (
            parameter["doc_type"]
            or parameter["type"]
            or "未声明"
        )

        required_text = "是"

        if not parameter["required"]:
            required_text = "否"

        default_text = parameter["default"]

        if not default_text:
            if parameter["kind"] == "vararg":
                default_text = "*args"
            elif parameter["kind"] == "kwarg":
                default_text = "**kwargs"
            else:
                default_text = "—"

        description = parameter["description"]

        if not description:
            description = "源码暂未提供单独参数说明。"

        lines.append(
            "| `{}` | `{}` | {} | `{}` | {} |".format(
                escape_table_text(
                    parameter["name"]
                ),
                escape_table_text(
                    parameter_type
                ),
                required_text,
                escape_table_text(
                    default_text
                ),
                escape_table_text(
                    description
                )
            )
        )

    lines.append("")
    return lines


def append_callable_markdown(
        lines,
        module_info,
        callable_info,
        heading_level,
        class_info=None
):
    """把一个 Function / Method 的完整 API 文档追加到 Markdown。"""
    heading = "#" * heading_level

    lines.append(
        "{} `{}`".format(
            heading,
            callable_info["name"] + "()"
        )
    )
    lines.append("")

    summary = callable_info["summary"]

    if not summary:
        summary = "源码暂未提供详细功能摘要。"

    lines.append(
        summary
    )
    lines.append("")

    if callable_info["usage"]:
        lines.append(
            "**适用场景**"
        )
        lines.append("")
        lines.append(
            callable_info["usage"]
        )
        lines.append("")

    if callable_info["body"]:
        lines.append(
            callable_info["body"]
        )
        lines.append("")

    # -------------------------------------------------------------------------
    # Signature
    # -------------------------------------------------------------------------
    lines.append(
        "**Signature**"
    )
    lines.append("")
    lines.append("```python")
    lines.append(
        callable_info["signature"]
    )
    lines.append("```")
    lines.append("")

    # -------------------------------------------------------------------------
    # 参数
    # -------------------------------------------------------------------------
    lines.append(
        "**参数**"
    )
    lines.append("")
    parameter_lines = build_parameter_table(
        callable_info
    )

    for parameter_line in parameter_lines:
        lines.append(
            parameter_line
        )

    # -------------------------------------------------------------------------
    # 返回值
    # -------------------------------------------------------------------------
    lines.append(
        "**返回值**"
    )
    lines.append("")

    if callable_info["returns"]:
        lines.append(
            callable_info["returns"]
        )
    elif callable_info["return_annotation"]:
        lines.append(
            "返回类型：`{}`。源码暂未提供更详细的返回值说明。".format(
                callable_info[
                    "return_annotation"
                ]
            )
        )
    else:
        lines.append(
            "源码未声明返回值说明。"
        )

    lines.append("")

    # -------------------------------------------------------------------------
    # 异常
    # -------------------------------------------------------------------------
    lines.append(
        "**异常**"
    )
    lines.append("")

    if callable_info["raises"]:
        for raise_info in callable_info["raises"]:
            description = raise_info[
                "description"
            ]

            if not description:
                description = "源码未提供进一步说明。"

            lines.append(
                "- `{}`：{}".format(
                    raise_info["type"],
                    description
                )
            )
    else:
        lines.append(
            "源码未声明专门的异常说明。"
        )

    lines.append("")

    # -------------------------------------------------------------------------
    # 示例
    # -------------------------------------------------------------------------
    lines.append(
        "**示例**"
    )
    lines.append("")

    if callable_info["examples"]:
        lines.append(
            build_docstring_example(
                callable_info["examples"]
            )
        )
    else:
        lines.append(
            build_callable_example(
                module_info,
                callable_info,
                class_info=class_info
            )
        )

    lines.append("")

    # -------------------------------------------------------------------------
    # Notes
    # -------------------------------------------------------------------------
    if callable_info["notes"]:
        lines.append(
            '!!! note "说明"'
        )

        for note_line in callable_info["notes"].splitlines():
            lines.append(
                "    " + note_line
            )

        lines.append("")


