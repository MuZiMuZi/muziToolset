def format_ast_value(node):
    """把 AST 默认值 / Annotation 转成可读源码字符串。"""
    if node is None:
        return ""

    try:
        return ast.unparse(node)
    except Exception:
        return "..."


def get_function_parameters(function_node):
    """
    收集函数参数信息。

    Returns:
        list:
            每个元素都包含 name / type / default / required / kind。
    """
    parameters = []
    arguments = function_node.args

    all_positional = []

    for argument in arguments.posonlyargs:
        all_positional.append(
            ("positional_only", argument)
        )

    for argument in arguments.args:
        all_positional.append(
            ("positional", argument)
        )

    default_count = len(
        arguments.defaults
    )
    first_default_index = len(all_positional) - default_count

    for argument_index, parameter_data in enumerate(all_positional):
        parameter_kind = parameter_data[0]
        argument = parameter_data[1]

        default_text = ""
        required = True

        if argument_index >= first_default_index:
            default_index = argument_index - first_default_index
            default_node = arguments.defaults[
                default_index
            ]
            default_text = format_ast_value(
                default_node
            )
            required = False

        annotation_text = format_ast_value(
            argument.annotation
        )

        parameters.append({
            "name": argument.arg,
            "type": annotation_text,
            "default": default_text,
            "required": required,
            "kind": parameter_kind,
        })

    if arguments.vararg is not None:
        parameters.append({
            "name": arguments.vararg.arg,
            "type": format_ast_value(
                arguments.vararg.annotation
            ),
            "default": "",
            "required": False,
            "kind": "vararg",
        })

    for keyword_index, argument in enumerate(arguments.kwonlyargs):
        default_node = arguments.kw_defaults[
            keyword_index
        ]

        default_text = ""
        required = True

        if default_node is not None:
            default_text = format_ast_value(
                default_node
            )
            required = False

        parameters.append({
            "name": argument.arg,
            "type": format_ast_value(
                argument.annotation
            ),
            "default": default_text,
            "required": required,
            "kind": "keyword_only",
        })

    if arguments.kwarg is not None:
        parameters.append({
            "name": arguments.kwarg.arg,
            "type": format_ast_value(
                arguments.kwarg.annotation
            ),
            "default": "",
            "required": False,
            "kind": "kwarg",
        })

    return parameters


def format_function_signature(function_node):
    """根据 AST FunctionDef 生成函数签名。"""
    parameters = get_function_parameters(
        function_node
    )
    parameter_texts = []

    has_vararg = False
    keyword_only_started = False

    for parameter in parameters:
        name = parameter["name"]
        parameter_type = parameter["type"]
        default_text = parameter["default"]
        parameter_kind = parameter["kind"]

        if parameter_kind == "vararg":
            text = "*" + name
            has_vararg = True

        elif parameter_kind == "kwarg":
            text = "**" + name

        else:
            if parameter_kind == "keyword_only":
                if not has_vararg and not keyword_only_started:
                    parameter_texts.append(
                        "*"
                    )
                    keyword_only_started = True

            text = name

        if parameter_type:
            text += ": " + parameter_type

        if default_text:
            text += "=" + default_text

        parameter_texts.append(
            text
        )

    signature = "{}({})".format(
        function_node.name,
        ", ".join(parameter_texts)
    )

    if function_node.returns is not None:
        signature += " -> " + format_ast_value(
            function_node.returns
        )

    return signature


def build_callable_info(function_node):
    """把 Function / Method AST 节点整理成文档数据。"""
    docstring = ast.get_docstring(
        function_node
    ) or ""

    sections = split_docstring_sections(
        docstring
    )

    argument_descriptions = parse_argument_descriptions(
        sections["args"]
    )

    parameters = get_function_parameters(
        function_node
    )

    for parameter in parameters:
        parameter_name = parameter["name"]

        description_info = argument_descriptions.get(
            parameter_name
        )

        parameter["description"] = ""

        if description_info:
            if description_info["type"]:
                parameter["doc_type"] = description_info["type"]
            else:
                parameter["doc_type"] = ""

            parameter["description"] = description_info[
                "description"
            ]
        else:
            parameter["doc_type"] = ""

    return {
        "name": function_node.name,
        "signature": format_function_signature(
            function_node
        ),
        "docstring": docstring,
        "summary": sections["summary"],
        "body": sections["body"],
        "parameters": parameters,
        "returns": sections["returns"],
        "raises": parse_raises(
            sections["raises"]
        ),
        "examples": sections["examples"],
        "notes": sections["notes"],
        "usage": sections["usage"],
        "return_annotation": format_ast_value(
            function_node.returns
        ),
        "lineno": getattr(
            function_node,
            "lineno",
            None
        ),
    }


def collect_class_api(class_node):
    """收集公开类、构造函数和公开方法。"""
    methods = []
    constructor = None

    for child_node in class_node.body:
        if not isinstance(
                child_node,
                (ast.FunctionDef, ast.AsyncFunctionDef)
        ):
            continue

        if child_node.name == "__init__":
            constructor = build_callable_info(
                child_node
            )
            continue

        if child_node.name.startswith("_"):
            continue

        method_info = build_callable_info(
            child_node
        )
        methods.append(
            method_info
        )

    class_docstring = ast.get_docstring(
        class_node
    ) or ""

    class_sections = split_docstring_sections(
        class_docstring
    )

    return {
        "name": class_node.name,
        "docstring": class_docstring,
        "summary": class_sections["summary"],
        "body": class_sections["body"],
        "notes": class_sections["notes"],
        "usage": class_sections["usage"],
        "constructor": constructor,
        "methods": methods,
        "lineno": getattr(
            class_node,
            "lineno",
            None
        ),
    }


def collect_module_info(project_root, source_path):
    """解析一个 Python 文件，并收集模块级 API 信息。"""
    source_text = read_source_text(
        source_path
    )

    module_tree = ast.parse(
        source_text,
        filename=source_path
    )

    relative_path = os.path.relpath(
        source_path,
        project_root
    ).replace(
        "\\",
        "/"
    )

    path_parts = relative_path.split(
        "/"
    )

    if len(path_parts) == 1:
        root_name = "package"
    else:
        root_name = path_parts[0]

    module_docstring = ast.get_docstring(
        module_tree
    ) or ""

    module_sections = split_docstring_sections(
        module_docstring
    )

    module_info = {
        "source_path": source_path,
        "relative_path": relative_path,
        "root_name": root_name,
        "module_name": source_path_to_module_name(
            project_root,
            source_path
        ),
        "module_docstring": module_docstring,
        "summary": module_sections["summary"],
        "body": module_sections["body"],
        "notes": module_sections["notes"],
        "usage": module_sections["usage"],
        "functions": [],
        "classes": [],
        "constants": [],
    }

    # -------------------------------------------------------------------------
    # 公开顶层 Function / Class。
    # -------------------------------------------------------------------------
    for node in module_tree.body:
        if isinstance(
                node,
                (ast.FunctionDef, ast.AsyncFunctionDef)
        ):
            if node.name.startswith("_"):
                continue

            module_info["functions"].append(
                build_callable_info(
                    node
                )
            )

        elif isinstance(node, ast.ClassDef):
            if node.name.startswith("_"):
                continue

            module_info["classes"].append(
                collect_class_api(
                    node
                )
            )

        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            constant_name = None
            constant_value = ""

            if isinstance(node, ast.Assign):
                if len(node.targets) == 1:
                    target = node.targets[0]

                    if isinstance(target, ast.Name):
                        constant_name = target.id

                constant_value = format_ast_value(
                    node.value
                )

            else:
                if isinstance(node.target, ast.Name):
                    constant_name = node.target.id

                constant_value = format_ast_value(
                    node.value
                )

            if not constant_name:
                continue

            if constant_name.startswith("_"):
                continue

            # 只把全大写或明显配置表暴露到模块常量区域。
            if constant_name.isupper():
                module_info["constants"].append({
                    "name": constant_name,
                    "value": constant_value,
                })

    return module_info


