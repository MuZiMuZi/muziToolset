    scenarios = []

    # -------------------------------------------------------------------------
    # 步骤 1：按架构层级给出通用使用场景。
    # -------------------------------------------------------------------------
    if root_name == "core":
        scenarios.append("需要在多个 Tool / System 中复用同一套 Maya 底层能力时。")
