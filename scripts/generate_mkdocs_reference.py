def write_text_file(file_path, content):
    """写入 UTF-8 文本，并自动创建父目录。"""
    parent_directory = os.path.dirname(file_path)

    if not os.path.isdir(parent_directory):
        os.makedirs(parent_directory)

    with open(file_path, "w", encoding="utf-8", newline="\n") as file_object:
        file_object.write(content)


def get_output_relative_path(module_info):
    """计算一个源码模块对应的 docs/reference 下输出路径。"""
    relative_source = module_info["relative_path"]
    relative_without_extension = os.path.splitext(relative_source)[0]
    return relative_without_extension + ".md"


def build_reference_index(title, description, module_items, docs_root):
    """生成一个 Reference 分类索引 Markdown。"""
    lines = []
    lines.append(generated_marker)
    lines.append("")
    lines.append("# {}".format(title))
    lines.append("")
    lines.append(description)
    lines.append("")
    lines.append("| 模块 | 源码 |")
    lines.append("| --- | --- |")

    for module_info, output_path in module_items:
        index_directory = os.path.join(
            docs_root,
            "reference",
            module_info["root_name"]
        )

        relative_link = os.path.relpath(
            output_path,
            index_directory
        ).replace("\\", "/")

        lines.append(
            "| [`{}`]({}) | `{}` |".format(
                module_info["module_name"],
                relative_link,
                module_info["relative_path"]
            )
        )

    lines.append("")
    return "\n".join(lines)


def clean_generated_reference(reference_root):
    """
    删除旧自动生成模块页。

    注意：
        这里只删除含 generated_marker 的 .md，避免误删开发者手写文档。
    """
    if not os.path.isdir(reference_root):
        return

    for root_directory, folder_names, file_names in os.walk(reference_root):
        for file_name in file_names:
            if not file_name.endswith(".md"):
                continue

            file_path = os.path.join(
                root_directory,
                file_name
            )

            try:
                with open(file_path, "r", encoding="utf-8") as file_object:
                    first_content = file_object.read(512)
            except OSError:
                continue

            if generated_marker not in first_content:
                continue

            os.remove(file_path)

    # 清理被生成器留下的空目录，但保留 reference 根目录本身。
    for root_directory, folder_names, file_names in os.walk(
            reference_root,
            topdown=False
    ):
        if root_directory == reference_root:
            continue

        if os.listdir(root_directory):
            continue

        shutil.rmtree(root_directory)


def generate_reference_docs(project_root=None):
    """
    扫描正式源码并生成全部 MkDocs API Reference。

    Returns:
        dict: generated_modules / output_files。
    """
    # -------------------------------------------------------------------------
    # 步骤 1：确定项目和文档目录。
    # -------------------------------------------------------------------------
    if project_root is None:
        project_root = get_project_root()

    docs_root = get_docs_root(project_root)
    reference_root = os.path.join(
        docs_root,
        "reference"
    )

    # -------------------------------------------------------------------------
    # 步骤 2：清理上一轮自动生成文件。
    # -------------------------------------------------------------------------
    clean_generated_reference(reference_root)

    # -------------------------------------------------------------------------
    # 步骤 3：扫描并解析全部正式 Python 模块。
    # -------------------------------------------------------------------------
    source_files = iter_source_files(project_root)
    module_infos = []

    for source_path in source_files:
        module_info = collect_module_info(
            project_root,
            source_path
        )
        module_infos.append(module_info)

    output_files = []
    category_items = {
        "core": [],
        "tools": [],
        "systems": [],
    }

    # -------------------------------------------------------------------------
    # 步骤 4：逐模块生成 Markdown 页面。
    # -------------------------------------------------------------------------
    for module_info in module_infos:
        output_relative_path = get_output_relative_path(module_info)
        output_path = os.path.join(
            reference_root,
            output_relative_path
        )

        markdown_content = build_module_markdown(module_info)
        write_text_file(
            output_path,
            markdown_content
        )

        output_files.append(output_path)
        category_items[module_info["root_name"]].append(
            (module_info, output_path)
        )

    # -------------------------------------------------------------------------
    # 步骤 5：为三个正式层级生成分类 Index。
    # -------------------------------------------------------------------------
    category_settings = {
        "core": (
            "Core API",
            "Core 是 MuziTools 的 Maya 通用底层能力层，不包含 PySide UI 和完整 Rig Workflow。",
        ),
        "tools": (
            "Tools API",
            "Tools 是用户可以直接打开的小工具，主要负责 UI、Selection 和调用 Core / Systems。",
        ),
        "systems": (
            "Systems API",
            "Systems 是可复用的完整 Rig Builder / Workflow，例如 Controller、Face 和 Body 组件。",
        ),
    }

    for category_name in source_roots:
        title, description = category_settings[category_name]
        index_content = build_reference_index(
            title,
            description,
            category_items[category_name],
            docs_root
        )

        index_path = os.path.join(
            reference_root,
            category_name,
            "index.md"
        )
        write_text_file(
            index_path,
            index_content
        )
        output_files.append(index_path)

    return {
        "generated_modules": len(module_infos),
        "output_files": output_files,
    }


