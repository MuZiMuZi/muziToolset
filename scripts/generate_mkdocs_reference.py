def build_api_navigation(module_infos):
    """
    生成 API Reference 的分类统计。

    MkDocs 真正的左侧导航由 SUMMARY.md 提供。
    """
    category_names = [
        "app",
        "core",
        "systems",
        "tools",
        "ui",
        "package",
    ]

    navigation = {}

    for category_name in category_names:
        navigation[category_name] = []

    for module_info in module_infos:
        category_name = module_info[
            "root_name"
        ]

        if category_name not in navigation:
            navigation[category_name] = []

        navigation[category_name].append(
            module_info["relative_path"]
        )

    for category_name in navigation:
        navigation[category_name].sort()

    return navigation


