# Docstring / AST Helper
# =============================================================================

def get_first_paragraph(docstring):
    """从 Docstring 中提取第一段非空文本作为功能摘要。"""
    if not docstring:
        return "当前源码没有模块说明，建议后续补充详细 Docstring。"

    lines = docstring.strip().splitlines()
    paragraph_lines = []

    for line in lines:
        stripped_line = line.strip()

        if not stripped_line:
            if paragraph_lines:
                break
            continue

        # 常见标题下划线不作为摘要正文。
        if set(stripped_line) == set("="):
            continue
        if set(stripped_line) == set("-"):
            continue

        paragraph_lines.append(stripped_line)

    if not paragraph_lines:
        return "当前源码没有可提取的模块摘要。"

    return " ".join(paragraph_lines)


def get_node_doc_summary(node):
    """取得函数或类 Docstring 的第一段摘要。"""
    docstring = ast.get_docstring(node)
    return get_first_paragraph(docstring)


def format_ast_value(node):
    """将 AST 默认值 / Annotation 转成可读源码字符串。"""
    if node is None:
        return ""

    # Python 3.9+ 提供 ast.unparse，Maya 2023 可以使用。
    try:
        return ast.unparse(node)
    except Exception:
        return "..."


def format_function_signature(function_node):
    """
    根据 AST FunctionDef / AsyncFunctionDef 生成可读函数签名。

    这里不执行源码，因此即使函数参数默认值依赖 Maya，也不会产生副作用。
    """
    arguments = function_node.args
    positional_arguments = []

    # -------------------------------------------------------------------------
    # 步骤 1：计算普通参数与默认值的对应关系。
    # -------------------------------------------------------------------------
    all_positional = []

    for argument in arguments.posonlyargs:
        all_positional.append(argument)

    for argument in arguments.args:
        all_positional.append(argument)

    default_count = len(arguments.defaults)
    first_default_index = len(all_positional) - default_count

    for argument_index, argument in enumerate(all_positional):
        argument_text = argument.arg

        if argument.annotation is not None:
            argument_text += ": " + format_ast_value(argument.annotation)

        if argument_index >= first_default_index:
            default_index = argument_index - first_default_index
            default_value = arguments.defaults[default_index]
            argument_text += "=" + format_ast_value(default_value)

        positional_arguments.append(argument_text)

    # -------------------------------------------------------------------------
    # 步骤 2：处理 *args。
    # -------------------------------------------------------------------------
    if arguments.vararg is not None:
        vararg_text = "*" + arguments.vararg.arg

        if arguments.vararg.annotation is not None:
            vararg_text += ": " + format_ast_value(arguments.vararg.annotation)

        positional_arguments.append(vararg_text)
    elif arguments.kwonlyargs:
        # 没有 *args 但有 Keyword Only 参数，需要插入单独的 *。
        positional_arguments.append("*")

    # -------------------------------------------------------------------------
    # 步骤 3：处理 Keyword Only 参数。
    # -------------------------------------------------------------------------
    for keyword_index, argument in enumerate(arguments.kwonlyargs):
        argument_text = argument.arg

        if argument.annotation is not None:
            argument_text += ": " + format_ast_value(argument.annotation)

        default_value = arguments.kw_defaults[keyword_index]

        if default_value is not None:
            argument_text += "=" + format_ast_value(default_value)

        positional_arguments.append(argument_text)

    # -------------------------------------------------------------------------
    # 步骤 4：处理 **kwargs。
    # -------------------------------------------------------------------------
    if arguments.kwarg is not None:
        kwarg_text = "**" + arguments.kwarg.arg

        if arguments.kwarg.annotation is not None:
            kwarg_text += ": " + format_ast_value(arguments.kwarg.annotation)

        positional_arguments.append(kwarg_text)

    signature = "{}({})".format(
        function_node.name,
        ", ".join(positional_arguments)
    )

    if function_node.returns is not None:
        signature += " -> " + format_ast_value(function_node.returns)

    return signature


def collect_class_api(class_node):
    """
    收集一个公开类及其公开方法。

    Returns:
        dict: class_name / summary / methods。
    """
    methods = []

    for child_node in class_node.body:
        if not isinstance(child_node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue

        # __init__ 对理解类构造很重要，因此保留；其它私有方法不进入第一版 API。
        if child_node.name.startswith("_") and child_node.name != "__init__":
            continue

        method_info = {
            "name": child_node.name,
            "signature": format_function_signature(child_node),
            "summary": get_node_doc_summary(child_node),
        }
        methods.append(method_info)

    return {
        "name": class_node.name,
        "summary": get_node_doc_summary(class_node),
        "methods": methods,
    }


def collect_module_info(project_root, source_path):
    """
    解析一个 Python 模块并收集文档需要的信息。

    Returns:
        dict: 模块路径、Docstring、公开函数、公开类等。
    """
    # 步骤 1：读取源码，并使用 AST 解析。
    source_text = read_source_text(source_path)
    module_tree = ast.parse(
        source_text,
        filename=source_path
    )

    # 步骤 2：准备模块基础信息。
    relative_path = os.path.relpath(
        source_path,
        project_root
    ).replace("\\", "/")

    path_parts = relative_path.split("/")
    root_name = path_parts[0]

    module_info = {
        "source_path": source_path,
        "relative_path": relative_path,
        "root_name": root_name,
        "module_name": source_path_to_module_name(
            project_root,
            source_path
        ),
        "module_docstring": ast.get_docstring(module_tree) or "",
        "functions": [],
        "classes": [],
    }

    # 步骤 3：只收集模块顶层公开 Function / Class。
    for node in module_tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if node.name.startswith("_"):
                continue

            function_info = {
                "name": node.name,
                "signature": format_function_signature(node),
                "summary": get_node_doc_summary(node),
            }
            module_info["functions"].append(function_info)

        elif isinstance(node, ast.ClassDef):
            if node.name.startswith("_"):
                continue

            module_info["classes"].append(
                collect_class_api(node)
            )

    return module_info


