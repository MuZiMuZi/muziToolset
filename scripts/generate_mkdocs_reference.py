u"""
MkDocs Reference Generator
==========================

MuziTools 静态 API 文档生成器。

设计目标
--------
1. 不 import Maya / PySide 模块，只使用 Python AST；
2. 每一个正式运行时 Python 文件都有独立 API 页面；
3. 每一个公开 Function / Class / Method 都生成详细说明；
4. 自动展示 Signature、参数、默认值、返回值、异常、示例和 Notes；
5. 源码 Docstring 是文档的第一事实来源，生成器只做结构化展示；
6. 没有写完整 Docstring 时也能从 AST 生成安全的 API 骨架；
7. 文档目录尽量与源码目录一致，便于从文件快速定位到 API；
8. 复杂 Rig Workflow 仍保留手写 User Guide，不把教程和 API Reference 混在一起。

生成范围
--------
正式运行时模块：

    app/**/*.py
    core/**/*.py
    systems/**/*.py
    tools/**/*.py
    ui/**/*.py
    config.py

默认不扫描：

    legacy_reference/
    tests/
    scripts/
    __pycache__/

说明
----
``__init__.py`` 也属于正式 Python 文件，因此会生成 ``package.md``，
但不会与分类 ``index.md`` 冲突。

文档风格
--------
文档信息架构参考任务导向的用户手册思路：

    概览
    常用任务
    API 一览
    详细 API
    示例
    相关内容

API 页面内部则保持开发者参考所需的完整技术信息。
"""

