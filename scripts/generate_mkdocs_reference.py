def is_public_python_file(file_name):
    """
    判断一个文件是否属于正式 API 文档范围。

    Args:
        file_name (str):
            Python 文件名称。

    Returns:
        bool:
            可以生成 API 文档时返回 True。
    """
    if not file_name.endswith(".py"):
        return False

    # ``__init__.py`` 是 Package API 的组成部分，需要生成文档。
    if file_name == "__init__.py":
        return True

    # 私有模块不进入公开 API。
    if file_name.startswith("_"):
        return False

    return True


def iter_source_files(project_root):
    """
    扫描正式运行时 Python 模块。

    Args:
        project_root (str):
            MuziTools 仓库根目录。

    Returns:
        list:
            排序后的 Python 文件绝对路径。
    """
    source_files = []

    # -------------------------------------------------------------------------
    # 步骤 1：扫描 app / core / systems / tools / ui。
    # -------------------------------------------------------------------------
    for source_root_name in source_roots:
        source_root = os.path.join(
            project_root,
            source_root_name
        )

        if not os.path.isdir(source_root):
            continue

        for root_directory, folder_names, file_names in os.walk(source_root):
            ignored_folders = [
                "__pycache__",
            ]

            for ignored_folder in ignored_folders:
                if ignored_folder in folder_names:
                    folder_names.remove(
                        ignored_folder
                    )

            for file_name in file_names:
                if not is_public_python_file(file_name):
                    continue

                source_path = os.path.join(
                    root_directory,
                    file_name
                )
                source_files.append(
                    source_path
                )

    # -------------------------------------------------------------------------
    # 步骤 2：补充仓库根目录的正式独立模块。
    # -------------------------------------------------------------------------
    for file_name in root_module_files:
        source_path = os.path.join(
            project_root,
            file_name
        )

        if not os.path.isfile(source_path):
            continue

        source_files.append(
            source_path
        )

    source_files.sort()
    return source_files


def source_path_to_module_name(project_root, source_path):
    """
    将源码路径转换成真实 Python Import Path。

    Example:
        ``core/animation_utils.py``
        -> ``muziToolset.core.animation_utils``
    """
    relative_path = os.path.relpath(
        source_path,
        project_root
    )

    relative_path = relative_path.replace(
        "\\",
        "/"
    )

    if relative_path == "__init__.py":
        return "muziToolset"

    module_path = os.path.splitext(
        relative_path
    )[0]

    if module_path.endswith("/__init__"):
        module_path = module_path[:-len("/__init__")]

    module_path = module_path.replace(
        "/",
        "."
    )

    return "muziToolset." + module_path


def read_source_text(source_path):
    """读取 UTF-8 Python 源码。"""
    with open(
            source_path,
            "r",
            encoding="utf-8"
    ) as file_object:
        return file_object.read()


