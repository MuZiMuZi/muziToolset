def normalize_section_name(text):
    """把 Docstring 章节标题整理成生成器内部标准名称。"""
    if not text:
        return None

    normalized_text = text.strip()
    normalized_text = normalized_text.rstrip(":")
    normalized_text = normalized_text.lower()

    return section_aliases.get(
        normalized_text
    )


def split_docstring_sections(docstring):
    """
    将 Docstring 拆成 Summary / Body / Args / Returns / Raises / Examples 等区域。

    兼容常见 Google Style 和中文章节标题。
    """
    result = {
        "summary": "",
        "body": "",
        "args": "",
        "returns": "",
        "raises": "",
        "examples": "",
        "notes": "",
        "usage": "",
    }

    if not docstring:
        return result

    raw_lines = docstring.expandtabs(4).strip().splitlines()

    current_section = "body"
    section_lines = {
        "body": [],
        "args": [],
        "returns": [],
        "raises": [],
        "examples": [],
        "notes": [],
        "usage": [],
    }

    # -------------------------------------------------------------------------
    # 步骤 1：根据章节标题分组。
    # -------------------------------------------------------------------------
    for line in raw_lines:
        stripped_line = line.strip()
        section_name = normalize_section_name(
            stripped_line
        )

        if section_name:
            current_section = section_name
            continue

        section_lines[current_section].append(
            line.rstrip()
        )

    # -------------------------------------------------------------------------
    # 步骤 2：Body 第一段作为 Summary，其余保留为详细说明。
    # -------------------------------------------------------------------------
    body_lines = section_lines["body"]
    summary_lines = []
    remaining_lines = []
    summary_finished = False

    for line in body_lines:
        stripped_line = line.strip()

        if not stripped_line:
            if summary_lines:
                summary_finished = True
            continue

        # 常见标题下划线不进入摘要。
        if stripped_line:
            character_set = set(stripped_line)

            if character_set == set("="):
                continue

            if character_set == set("-"):
                continue

        if not summary_finished:
            summary_lines.append(
                stripped_line
            )
        else:
            remaining_lines.append(
                line
            )

    result["summary"] = " ".join(
        summary_lines
    ).strip()

    result["body"] = "\n".join(
        remaining_lines
    ).strip()

    for section_name in [
        "args",
        "returns",
        "raises",
        "examples",
        "notes",
        "usage",
    ]:
        result[section_name] = "\n".join(
            section_lines[section_name]
        ).strip()

    return result


def get_first_paragraph(docstring):
    """从 Docstring 中取得第一段功能摘要。"""
    sections = split_docstring_sections(
        docstring
    )

    if sections["summary"]:
        return sections["summary"]

    return "当前源码没有可提取的功能摘要。"


def parse_argument_descriptions(args_text):
    """
    解析 Google Style ``Args`` 章节。

    支持：

        node (str):
            Maya 节点名称。

        node:
            Maya 节点名称。
    """
    descriptions = {}

    if not args_text:
        return descriptions

    lines = args_text.splitlines()
    current_name = None
    current_description = []

    argument_pattern = re.compile(
        r"^\s*([*]{0,2}[A-Za-z_][A-Za-z0-9_]*)"
        r"(?:\s*\(([^)]*)\))?\s*:\s*(.*)$"
    )

    current_type = ""

    def save_current_argument():
        """把正在解析的参数保存到结果字典。"""
        if current_name is None:
            return

        description_text = " ".join(
            current_description
        ).strip()

        descriptions[current_name] = {
            "type": current_type or "",
            "description": description_text,
        }

    for line in lines:
        match = argument_pattern.match(
            line
        )

        if match:
            save_current_argument()

            current_name = match.group(1)
            current_name = current_name.lstrip("*")
            current_type = match.group(2) or ""

            current_description = []

            inline_description = match.group(3).strip()

            if inline_description:
                current_description.append(
                    inline_description
                )

            continue

        stripped_line = line.strip()

        if current_name is None:
            continue

        if not stripped_line:
            continue

        current_description.append(
            stripped_line
        )

    save_current_argument()
    return descriptions


def parse_raises(raises_text):
    """解析 Raises / 异常章节。"""
    result = []

    if not raises_text:
        return result

    lines = raises_text.splitlines()
    current_exception = None
    current_description = []

    exception_pattern = re.compile(
        r"^\s*([A-Za-z_][A-Za-z0-9_.]*)\s*:\s*(.*)$"
    )

    def save_current_exception():
        """保存当前异常说明。"""
        if current_exception is None:
            return

        result.append({
            "type": current_exception,
            "description": " ".join(
                current_description
            ).strip(),
        })

    for line in lines:
        match = exception_pattern.match(
            line
        )

        if match:
            save_current_exception()

            current_exception = match.group(1)
            current_description = []

            inline_description = match.group(2).strip()

            if inline_description:
                current_description.append(
                    inline_description
                )

            continue

        stripped_line = line.strip()

        if current_exception is None:
            continue

        if not stripped_line:
            continue

        current_description.append(
            stripped_line
        )

    save_current_exception()
    return result


