def generate_reference_docs(project_root=None):
    """
    扫描正式源码并生成全部详细 API Reference。

    Returns:
        dict:
            generated_modules / output_files / navigation。
    """
    if project_root is None:
        project_root = get_project_root()

    docs_root = get_docs_root(
        project_root
    )

    reference_root = os.path.join(
        docs_root,
        "reference"
    )

    clean_generated_reference(
        reference_root
    )

    source_files = iter_source_files(
        project_root
    )
    module_infos = []

    for source_path in source_files:
        module_info = collect_module_info(
            project_root,
            source_path
        )

        module_infos.append(
            module_info
        )

    output_files = []
    category_items = {
        "app": [],
        "core": [],
        "systems": [],
        "tools": [],
        "ui": [],
        "package": [],
    }

    for module_info in module_infos:
        output_relative_path = get_output_relative_path(
            module_info
        )

        output_path = os.path.join(
            reference_root,
            output_relative_path
        )

        markdown_content = build_module_markdown(
            module_info
        )

        write_text_file(
            output_path,
            markdown_content
        )

        output_files.append(
            output_path
        )

        category_name = module_info[
            "root_name"
        ]

        if category_name not in category_items:
            category_items[category_name] = []

        category_items[category_name].append(
            (
                module_info,
                output_path
            )
        )

    category_settings = {
        "app": (
            "App API",
            "App 层负责 MuziTools 主程序入口、工具箱和顶层窗口生命周期。"
        ),
        "core": (
            "Core API",
            "Core 是 Maya 通用底层能力层，不包含完整 Rig Workflow。"
        ),
        "systems": (
            "Systems API",
            "Systems 是可复用的完整 Rig Builder / Workflow。"
        ),
        "tools": (
            "Tools API",
            "Tools 是绑定师可以直接打开使用的小工具和操作面板。"
        ),
        "ui": (
            "UI API",
            "UI 层提供统一窗口、主题和可复用 PySide 组件。"
        ),
        "package": (
            "Package API",
            "MuziTools 根包和全局配置入口。"
        ),
    }

    for category_name in category_settings:
        module_items = category_items.get(
            category_name,
            []
        )

        if not module_items:
            continue

        title, description = category_settings[
            category_name
        ]

        index_content = build_reference_index(
            title,
            description,
            module_items,
            docs_root,
            category_name
        )

        if category_name == "package":
            index_path = os.path.join(
                reference_root,
                "package-index.md"
            )
        else:
            index_path = os.path.join(
                reference_root,
                category_name,
                "index.md"
            )

        write_text_file(
            index_path,
            index_content
        )

        output_files.append(
            index_path
        )

    navigation = build_api_navigation(
        module_infos
    )

    summary_path = write_summary_file(
        docs_root,
        module_infos
    )
    output_files.append(
        summary_path
    )

    return {
        "generated_modules": len(
            module_infos
        ),
        "output_files": output_files,
        "navigation": navigation,
        "summary_path": summary_path,
    }


